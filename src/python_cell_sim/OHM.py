## Bit Serial OHM Node with both LSB and MSB paths

from ADD import ADD
from PTF import PTF
from msb2lsb import msb2lsb
from lsb2msb import lsb2msb
import matplotlib.pyplot as plt
import matplotlib.patches as patches

class OHM:
    
    def __init__(self, D = 3, ptf="", debugDone=0, debugIndex=-1, verbosity=0) -> None:
        self.d = D        
        self.d2 = D*2
        self.dd = self.d2+2     # add 2 for mirrored input 

        self.debugDone = debugDone        
        self.debugIndex = debugIndex     
        self.verbosity = verbosity

        self.addp = [ADD() for _ in range(self.dd)] 
        self.lsb2msbs = [lsb2msb() for _ in range(self.dd)]        
        self.msb2lsb = msb2lsb()
        self.flags = list(self.dd * [0])
        self.pbf = PTF(self.dd)
        
        # Some presets for debugging`1`
        if ptf == "min":
            self.pbf.SetMin()
        elif ptf == "max":          
            self.pbf.SetMax()                           
        else:       
            self.pbf.SetMedian()                

        self.Reset()

    def ZeroState(self, K) -> None:
        myZero = [0] * K
        for i in range(self.dd):
            self.lsb2msbs[i].InitState(myZero, K, initMode=0)
        self.msb2lsb.InitState(myZero, K, initMode=0)

    def InitState(self, input, K) -> None:                        
        for i in range(self.dd):
            self.lsb2msbs[i].InitState(input, K, initMode=1)        
        self.msb2lsb.InitState(input, K, initMode=1)
        
    def GetState(self):
        #state, lenn = self.msb2lsb.GetTransitionState()
        state, lenn = self.msb2lsb.GetReadState()
        ss = self.msb2lsb.onSwitchStep

        return state, lenn, ss

    def Reset(self) -> None:
        self.flags = list(self.dd * [0])                        
        self.latchInput = list(self.dd * [0])
        self.pbf.Reset()
        self.msb2lsb.Reset()        
        self.done = 0
        self.debugTicks = 0        

        for i in range(self.dd):
            self.addp[i].Reset()                        
            self.lsb2msbs[i].Reset()            

    def doneOut(self) -> int:
        return self.done
                    
    def lsbOut(self) -> int:
        return self.msb2lsb.SwitchStep()

    def Output(self) -> int:
        return self.msb2lsb.Output()

    def pbfOut(self):
        return self.pbf.Output()
    
    ## Combinatorial stuff goes here    
    def Calc(self, u, ulsb, x, xlsb, ww) -> None:        
        # u: scalar input to cell 
        # ulsb: scalar control input 
        # x: State space size D (output from array of nodes)
        # xlsb: lsb generated by cell
        # ww: weights for mirrored input and state (size 2D+2)        
        
        assert len(ww) == self.dd, f"ww length {len(ww)} does not match expected {self.dd}"
        
        nx = [1-x[i] for i in range(len(x))]
        nu = 1-u 
        input = x + nx + [u] + [nu]
        lsbVal = xlsb + xlsb + [ulsb] + [ulsb]
        
        assert len(ww) == len(input)
        assert len(ww) == len(lsbVal)
        
        for i in range(self.dd):
                
            self.addp[i].Calc(input[i], ww[i], lsbVal[i])             

            if lsbVal[i] == 1:
                self.lsb2msbs[i].Switch()                                            
                self.flags[i] = 0                
                self.latchInput[i] = self.lsb2msbs[i].Output()         
            else:
                if self.flags[i] == 0:
                    self.latchInput[i] = self.lsb2msbs[i].Output()
                            
        # Calc PBF
        self.pbf.Calc(self.latchInput)

        if self.verbosity > 2:
            print(f"Input: {input} -- LSB: {lsbVal} -- WW: {ww} -- AddP: {[addp.Output() for addp in self.addp]} -- Latch: {self.latchInput} -- PBF: {self.pbf.Output()}")        
        
        for i in range(self.dd):
            if self.flags[i] == 0:
                if self.latchInput[i] != self.pbf.Output():
                    self.flags[i] = 1                    

        if self.debugDone <= 0:
            if self.done == 0:
                if (sum(self.flags) == (self.dd-1)):                
                    self.done = 1
                    self.msb2lsb.SetSwitchNext()
        else:
            if self.debugTicks > 0:                     
                if ((self.debugTicks+1) % self.debugDone) == 0:
                    self.done = 1
                    self.msb2lsb.SetSwitchNext()
                        
        
    # State stuff goes here
    def Step(self) -> None:        
        self.debugTicks += 1
        #if self.done:

        # Reset done
        self.done = 0

        #print(f"OHM STEP t={self.debugTicks}")        
        if self.msb2lsb.SwitchStep() == 1:
            # back to twos before entry! 
            self.msb2lsb.Step(1 - self.pbf.Output())                                       
        else:
            self.msb2lsb.Step(self.pbf.Output())
            #self.done = 0

        for i in range(self.dd):
            self.lsb2msbs[i].Step(self.addp[i].Output())                                     
            self.addp[i].Step()                  

    def Print(self, prefix="", showInput=1, showOutput=1) -> None:
        
        print(f"{prefix} - Node {self.debugIndex} -- Done {self.done}---------------------------")
        if showInput:            
            for i in range(self.dd):                
                inputPrefix = f"   x{i}-"                
                #self.addp[i].Print(prefix)
                self.lsb2msbs[i].Print()                        
        if showOutput:            
            #print(f"- Output ---------")
            self.pbf.Print(" ")
            self.msb2lsb.Print()        
            print(f"------------------------------------")


